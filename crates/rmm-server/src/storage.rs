//! Object storage for ticket attachments and raw email: a local directory by default, or an
//! S3-compatible bucket (AWS S3, MinIO, ...) when `RMM_S3_BUCKET` is set.
//!
//! The S3 client is a small SigV4 implementation over the shared HTTP client (PUT, GET,
//! DELETE), which is all this needs.

use std::path::PathBuf;

use anyhow::{Context, Result, bail};
use chrono::Utc;
use hmac::{Hmac, KeyInit, Mac};
use sha2::{Digest, Sha256};

pub enum Storage {
    Local(PathBuf),
    S3(S3),
}

pub struct S3 {
    http: reqwest::Client,
    /// `https://s3.eu-west-1.amazonaws.com` or a MinIO URL, without a trailing slash.
    endpoint: String,
    bucket: String,
    region: String,
    access_key: String,
    secret_key: String,
    /// `endpoint/bucket/key` (MinIO, most self-hosted stores) instead of `bucket.endpoint/key`.
    path_style: bool,
}

/// Keys are generated by the server (`attachments/<uuid>`), but check anyway: no traversal,
/// nothing that needs escaping.
fn check_key(key: &str) -> Result<()> {
    let ok = !key.is_empty()
        && key.len() <= 512
        && key.split('/').all(|seg| !seg.is_empty() && seg != "." && seg != "..")
        && key.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'/' | b'-' | b'_' | b'.'));
    if !ok {
        bail!("invalid storage key {key:?}");
    }
    Ok(())
}

impl Storage {
    /// From the environment: `RMM_S3_BUCKET` (+ `RMM_S3_ENDPOINT`, `RMM_S3_REGION`,
    /// `RMM_S3_PATH_STYLE`, `AWS_ACCESS_KEY_ID`, `AWS_SECRET_ACCESS_KEY`), else `local_dir`.
    pub fn from_env(local_dir: PathBuf, http: reqwest::Client) -> Result<Self> {
        let var = |k: &str| std::env::var(k).ok().map(|v| v.trim().to_string()).filter(|v| !v.is_empty());
        let Some(bucket) = var("RMM_S3_BUCKET") else {
            return Ok(Storage::Local(local_dir));
        };
        let region = var("RMM_S3_REGION").or_else(|| var("AWS_REGION")).unwrap_or_else(|| "us-east-1".into());
        let custom = var("RMM_S3_ENDPOINT");
        let path_style = match var("RMM_S3_PATH_STYLE").as_deref() {
            Some("true" | "1") => true,
            Some("false" | "0") => false,
            Some(v) => bail!("RMM_S3_PATH_STYLE must be true or false, not {v}"),
            None => custom.is_some(),
        };
        let endpoint = custom.unwrap_or_else(|| format!("https://s3.{region}.amazonaws.com")).trim_end_matches('/').to_string();
        reqwest::Url::parse(&endpoint).context("RMM_S3_ENDPOINT")?;
        Ok(Storage::S3(S3 {
            http,
            endpoint,
            bucket,
            region,
            access_key: var("AWS_ACCESS_KEY_ID").context("RMM_S3_BUCKET is set but AWS_ACCESS_KEY_ID isn't")?,
            secret_key: var("AWS_SECRET_ACCESS_KEY").context("RMM_S3_BUCKET is set but AWS_SECRET_ACCESS_KEY isn't")?,
            path_style,
        }))
    }

    pub fn describe(&self) -> String {
        match self {
            Storage::Local(dir) => format!("directory {}", dir.display()),
            Storage::S3(s) => format!("s3 bucket {} at {}", s.bucket, s.endpoint),
        }
    }

    pub async fn put(&self, key: &str, bytes: Vec<u8>, content_type: &str) -> Result<()> {
        check_key(key)?;
        match self {
            Storage::Local(dir) => {
                let path = dir.join(key);
                if let Some(parent) = path.parent() {
                    tokio::fs::create_dir_all(parent).await.with_context(|| format!("creating {}", parent.display()))?;
                }
                // Write beside it and rename, so a crash never leaves half a file under the key.
                let tmp = path.with_extension("partial");
                tokio::fs::write(&tmp, &bytes).await.with_context(|| format!("writing {}", tmp.display()))?;
                tokio::fs::rename(&tmp, &path).await?;
                Ok(())
            }
            Storage::S3(s) => s.request(reqwest::Method::PUT, key, Some((bytes, content_type))).await.map(drop),
        }
    }

    pub async fn get(&self, key: &str) -> Result<Vec<u8>> {
        check_key(key)?;
        match self {
            Storage::Local(dir) => tokio::fs::read(dir.join(key)).await.with_context(|| format!("reading {key}")),
            Storage::S3(s) => s.request(reqwest::Method::GET, key, None).await,
        }
    }

    pub async fn delete(&self, key: &str) -> Result<()> {
        check_key(key)?;
        match self {
            Storage::Local(dir) => match tokio::fs::remove_file(dir.join(key)).await {
                Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(e.into()),
                _ => Ok(()),
            },
            Storage::S3(s) => s.request(reqwest::Method::DELETE, key, None).await.map(drop),
        }
    }
}

type HmacSha256 = Hmac<Sha256>;

fn hmac(key: &[u8], data: &str) -> Vec<u8> {
    let mut m = HmacSha256::new_from_slice(key).expect("HMAC accepts any key length");
    m.update(data.as_bytes());
    m.finalize().into_bytes().to_vec()
}

fn sha256_hex(data: &[u8]) -> String {
    hex::encode(Sha256::digest(data))
}

/// The SigV4 `Authorization` header for a request. `headers` must be lowercase names, sorted,
/// and include `host`, `x-amz-content-sha256` and `x-amz-date`.
#[allow(clippy::too_many_arguments)]
fn sigv4(
    method: &str,
    path: &str,
    headers: &[(&str, String)],
    payload_hash: &str,
    amz_date: &str,
    region: &str,
    access_key: &str,
    secret_key: &str,
) -> String {
    let date = &amz_date[..8];
    let canonical_headers: String = headers.iter().map(|(k, v)| format!("{k}:{}\n", v.trim())).collect();
    let signed_headers = headers.iter().map(|(k, _)| *k).collect::<Vec<_>>().join(";");
    let canonical = format!("{method}\n{path}\n\n{canonical_headers}\n{signed_headers}\n{payload_hash}");
    let scope = format!("{date}/{region}/s3/aws4_request");
    let to_sign = format!("AWS4-HMAC-SHA256\n{amz_date}\n{scope}\n{}", sha256_hex(canonical.as_bytes()));
    let k = hmac(format!("AWS4{secret_key}").as_bytes(), date);
    let k = hmac(&k, region);
    let k = hmac(&k, "s3");
    let k = hmac(&k, "aws4_request");
    let signature = hex::encode(hmac(&k, &to_sign));
    format!("AWS4-HMAC-SHA256 Credential={access_key}/{scope}, SignedHeaders={signed_headers}, Signature={signature}")
}

impl S3 {
    async fn request(&self, method: reqwest::Method, key: &str, body: Option<(Vec<u8>, &str)>) -> Result<Vec<u8>> {
        let base = reqwest::Url::parse(&self.endpoint)?;
        let host_only = base.host_str().context("S3 endpoint has no host")?;
        let host = match base.port() {
            Some(p) => format!("{host_only}:{p}"),
            None => host_only.to_string(),
        };
        // Keys are restricted to URL-safe characters (check_key), so no escaping is needed.
        let (host, path) =
            if self.path_style { (host, format!("/{}/{key}", self.bucket)) } else { (format!("{}.{host}", self.bucket), format!("/{key}")) };
        let url = format!("{}://{host}{path}", base.scheme());
        let payload_hash = sha256_hex(body.as_ref().map(|b| b.0.as_slice()).unwrap_or_default());
        let amz_date = Utc::now().format("%Y%m%dT%H%M%SZ").to_string();
        let mut headers = vec![("host", host.clone()), ("x-amz-content-sha256", payload_hash.clone()), ("x-amz-date", amz_date.clone())];
        if let Some((_, ct)) = &body {
            headers.insert(0, ("content-type", ct.to_string()));
        }
        let auth = sigv4(method.as_str(), &path, &headers, &payload_hash, &amz_date, &self.region, &self.access_key, &self.secret_key);
        let mut req = self.http.request(method.clone(), &url).header("authorization", auth);
        for (k, v) in &headers {
            if *k != "host" {
                req = req.header(*k, v);
            }
        }
        if let Some((bytes, _)) = body {
            req = req.body(bytes);
        }
        let res = req.send().await.with_context(|| format!("S3 {method} {key}"))?;
        let status = res.status();
        let bytes = res.bytes().await?.to_vec();
        if !status.is_success() && !(method == reqwest::Method::DELETE && status.as_u16() == 404) {
            bail!("S3 {method} {key}: HTTP {status}: {}", String::from_utf8_lossy(&bytes).chars().take(300).collect::<String>());
        }
        Ok(bytes)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_checked() {
        assert!(check_key("attachments/0b1c/abc.bin").is_ok());
        for bad in ["", "../x", "a//b", "a/./b", "a b", "a/..", "x?y", "/abs"] {
            assert!(check_key(bad).is_err(), "{bad}");
        }
    }

    /// The "GET Object" example from the AWS SigV4 documentation.
    #[test]
    fn sigv4_matches_aws_example() {
        let empty = sha256_hex(b"");
        let headers = vec![
            ("host", "examplebucket.s3.amazonaws.com".to_string()),
            ("range", "bytes=0-9".to_string()),
            ("x-amz-content-sha256", empty.clone()),
            ("x-amz-date", "20130524T000000Z".to_string()),
        ];
        let auth = sigv4(
            "GET",
            "/test.txt",
            &headers,
            &empty,
            "20130524T000000Z",
            "us-east-1",
            "AKIAIOSFODNN7EXAMPLE",
            "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY",
        );
        assert_eq!(
            auth,
            "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20130524/us-east-1/s3/aws4_request, \
             SignedHeaders=host;range;x-amz-content-sha256;x-amz-date, \
             Signature=f0e8bdb87c964420e857bd35b5d6ed310bd44f0170aba48dd91039c6036bdb41"
        );
    }

    #[tokio::test]
    async fn local_roundtrip() {
        let dir = std::env::temp_dir().join(format!("rmm-storage-{}", uuid::Uuid::new_v4().simple()));
        let s = Storage::Local(dir.clone());
        s.put("a/b.txt", b"hello".to_vec(), "text/plain").await.unwrap();
        assert_eq!(s.get("a/b.txt").await.unwrap(), b"hello");
        s.delete("a/b.txt").await.unwrap();
        s.delete("a/b.txt").await.unwrap();
        assert!(s.get("a/b.txt").await.is_err());
        let _ = std::fs::remove_dir_all(dir);
    }
}
